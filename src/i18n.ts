export type Language = 'auto' | 'en' | 'zh';
export type Translate = (key: Key) => string;
export function translator(language: Language, appLanguage: string): Translate {
  const chinese = language === 'zh' || (language === 'auto' && appLanguage.startsWith('zh'));
  return key => chinese ? zh[key] : en[key];
}
